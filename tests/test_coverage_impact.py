SOURCE = """module leaf(input wire a, input wire b, output wire q);
wire branch_a;
assign branch_a = a;
wire branch_b;
assign branch_b = b;
assign q = branch_a | branch_b;
endmodule
"""


def record(ctx, test, counts, seed=1):
    payload = {"covergroups": [{"name": f"line{line}", "source": f"rtl/leaf.sv:{line}",
        "coverpoints": [{"name": "cp", "bins": [{"name": "bin", "hits": hits}]}]}
        for line, hits in counts.items()]}
    (Path(ctx.ws.root) / "coverage-input.json").write_text(json.dumps(payload))
    result = cov_run(ctx, test, seed=seed)
    assert "error" not in result, result
    return result["job"]


def change_source(ctx, old=SOURCE, new=None):
    new = new or old.replace("assign branch_a = a;", "assign branch_a = ~a;")
    (Path(ctx.ws.root) / "rtl/leaf.sv").write_text(new)
    return FileChange("rtl/leaf.sv", "modified", old, new)


def test_line_hits_outrank_unrelated_bins_and_pin_evidence(coverage_adapter):
    ctx = coverage_adapter
    change_source(ctx, new=SOURCE)
    other = record(ctx, "unrelated", {3: 0, 5: 100, 6: 100})
    focused = record(ctx, "focused", {3: 1, 5: 0, 6: 0})
    order = CoverageHistory(ctx).order(["unrelated", "focused"], Diff([change_source(ctx)]))
    assert order["tests"] == ["focused", "unrelated"] and order["method"] == "coverage_lines"
    assert order["reasons"]["focused"]["changed_bins_hit"] == 1
    assert order["reasons"]["unrelated"]["changed_bins_hit"] == 0
    region = order["impact"]["regions"][0]
    assert region["old_lines"] == region["new_lines"] == [3, 3]
    assert region["status"] == "historical_hits" and region["tests"] == ["focused"]
    assert {e["job"] for e in region["evidence"]} == {focused, other}
    assert all(e["recorded_lines"] == [3] and e["side"] == "old" for e in region["evidence"])
    assert not order["impact"]["fallbacks"]


def test_source_snapshots_are_deduplicated_and_preserve_shifted_locations(coverage_adapter):
    ctx = coverage_adapter
    change_source(ctx, new=SOURCE)
    a = record(ctx, "focused", {3: 1})
    b = record(ctx, "unrelated", {3: 0})
    history = CoverageHistory(ctx)
    sa = history.load(a)[0]["source_snapshots"]["rtl/leaf.sv"]
    assert sa == history.load(b)[0]["source_snapshots"]["rtl/leaf.sv"]
    assert (Path(ctx.ws.root) / sa["path"]).read_text() == SOURCE
    baseline = "// committed header\n// another header\n" + SOURCE
    changed = change_source(ctx, old=baseline)
    order = history.order(["unrelated", "focused"], Diff([changed]))
    assert order["tests"] == ["focused", "unrelated"]
    region = order["impact"]["regions"][0]
    assert region["old_lines"] == region["new_lines"] == [5, 5]
    assert region["evidence"][0]["recorded_lines"] == [3]


@pytest.mark.parametrize("edit", ["insert", "delete", "unhit", "repeated", "macro", "generated"])
def test_gap_and_fallback_semantics(coverage_adapter, edit):
    ctx = coverage_adapter
    text = SOURCE
    if edit == "macro":
        text = '`define ENABLE 1\n' + text
    elif edit == "generated":
        text = '// Generated by a register tool; do not edit\n' + text
    elif edit == "repeated":
        text = text.replace("assign branch_b = b;", "assign branch_a = a;")
    change_source(ctx, new=text)
    line = text.splitlines().index("assign branch_a = a;") + 1
    record(ctx, "focused", {line: 0 if edit == "unhit" else 1})
    old, new = text, text.replace("assign branch_a = a;", "assign branch_a = ~a;", 1)
    if edit == "insert":
        new = text.replace("wire branch_b;", "wire extra;\nwire branch_b;")
    elif edit == "delete":
        new = text.replace("assign branch_a = a;\n", "")
    elif edit == "repeated":
        old = "// newer baseline\n" + text
        new = old.replace("assign branch_a = a;", "assign branch_a = ~a;", 1)
    changed = change_source(ctx, old=old, new=new)
    order = CoverageHistory(ctx).order(["focused"], Diff([changed]))
    region = order["impact"]["regions"][0]
    if edit == "delete":
        assert region["new_lines"] == [] and region["status"] == "historical_hits"
    elif edit == "unhit":
        assert region["status"] == "uncovered_bins" and region["unhit_bins"] == 1
        assert region["tests"] == [] and order["tests"] == ["focused"]
    else:
        assert region["status"] == "unknown" and region["evidence"] == []
        assert region["fallback_reasons"] and order["method"] == "coverage_history"


@pytest.mark.parametrize("mode", ["legacy", "modified", "missing"])
def test_untrusted_or_absent_source_snapshots_never_supply_line_evidence(coverage_adapter, mode):
    ctx = coverage_adapter
    change_source(ctx, new=SOURCE)
    job = record(ctx, "focused", {3: 1})
    history = CoverageHistory(ctx)
    data, rec = history.load(job)
    if mode == "legacy":
        # Simulate a genuine record written by the previous schema version.
        data["schema_version"] = 1
        del data["source_snapshots"]
        path = Path(ctx.ws.root) / rec.coverage_observation["path"]
        path.write_text(json.dumps(data))
        rec.coverage_observation["sha256"] = sha256_file(path)
        ctx.runner._persist(rec)
    else:
        path = Path(ctx.ws.root) / data["source_snapshots"]["rtl/leaf.sv"]["path"]
        if mode == "modified":
            path.write_text("wrong line identities")
        else:
            path.unlink()
    order = history.order(["focused"], Diff([change_source(ctx)]))
    assert order["method"] == "coverage_history"
    assert order["impact"]["regions"][0]["status"] == "unknown"
    assert not order["impact"]["regions"][0]["evidence"]
    assert history.compare(job, job)["delta_percent"] == 0


def test_new_observation_maps_new_lines_without_old_offset_guessing(coverage_adapter):
    ctx = coverage_adapter
    new = "// added line\n" + SOURCE.replace("assign branch_a = a;", "assign branch_a = ~a;")
    change_source(ctx, new=new)
    record(ctx, "focused", {4: 1})
    order = CoverageHistory(ctx).order(["focused"], Diff([FileChange("rtl/leaf.sv", "modified", SOURCE, new)]))
    region = next(r for r in order["impact"]["regions"] if r["change"] == "replace")
    assert region["new_lines"] == [4, 4] and region["old_lines"] == [3, 3]
    assert region["evidence"][0]["side"] == "new" and region["evidence"][0]["recorded_lines"] == [4]


def test_cli_saved_plan_reports_and_resume_preserve_matrix(coverage_adapter, fake_planner):
    ctx = coverage_adapter
    change_source(ctx, new=SOURCE)
    for args in (["init", "-q"], ["add", "rtl", "tb", ".chipchamp/config.toml", ".chipchamp/tests.yaml"],
                 ["-c", "user.name=Test", "-c", "user.email=test@example.invalid", "commit", "-qm", "baseline"]):
        subprocess.run(["git", "-C", ctx.ws.root, *args], check=True, capture_output=True)
    record(ctx, "focused", {3: 1})
    change_source(ctx)
    runner = CliRunner()
    args = ["--root", ctx.ws.root]
    planned = runner.invoke(cli, args + ["verify-plan", "--changed", "rtl/leaf.sv", "--out", "work/plan.json"])
    assert planned.exit_code == 0 and "old 3 -> new 3" in planned.output, planned.output
    assert "historical hits" in planned.output and "J-0001" in planned.output
    result = regress_run(ctx, plan_file="work/plan.json")
    # Both tops instantiate leaf indirectly/are conservative when the fixture's
    # changed module ports cause index uncertainty; exact saved selection wins.
    saved = json.loads((Path(ctx.ws.root) / "work/plan.json").read_text())
    assert result["total"] == len(saved["selection"]["selected_tests"]) * len(saved["seeds"])
    assert result["ordering"] == saved["ordering"]
    report = (Path(ctx.ws.root) / result["reports"]["markdown"]).read_text()
    assert "Change impact" in report and "old 3 -&gt; new 3" in report and "J-0001" in report
    again = regress_run(ctx, resume=result["checkpoint"])
    assert again["resumed"] == result["total"] and again["ordering"] == result["ordering"]
